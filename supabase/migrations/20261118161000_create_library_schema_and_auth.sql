create table public.members (
  id text primary key,
  nim text not null,
  nama text not null,
  prodi text not null,
  email text,
  no_hp text,
  rfid_tag text not null unique,
  status text not null check (status in ('Mahasiswa', 'Dosen', 'Visitor')),
  date_registered date not null default current_date
);

create table public.books (
  id text primary key,
  isbn text not null,
  judul text not null,
  pengarang text,
  penerbit text,
  kategori text,
  lokasi_rak text,
  rfid_tag text not null unique,
  epc_list text[] not null default array[]::text[],
  status text not null check (status in ('Tersedia', 'Dipinjam', 'Dalam Perawatan')) default 'Tersedia',
  stok integer not null default 0 check (stok >= 0)
);

create table public.visitor_logs (
  id text primary key,
  waktu text not null,
  nama text not null,
  nim text not null,
  prodi text not null,
  kategori text not null check (kategori in ('Mahasiswa', 'Dosen', 'Visitor')),
  status text not null check (status in ('Masuk', 'Keluar', 'Pinjam Buku')),
  rfid_tag text not null,
  email text,
  no_hp text
);

create table public.book_logs (
  id text primary key,
  waktu text not null,
  isbn text not null,
  judul text not null,
  kategori text,
  lokasi_rak text,
  rssi integer not null,
  rfid_tag text not null
);

create table public.activities (
  id text primary key,
  waktu text not null,
  deskripsi text not null,
  tipe text not null check (tipe in ('visitor', 'book', 'system', 'member')),
  icon_type text
);

create table public.rssi_history (
  id bigint generated by default as identity primary key,
  time text not null,
  rssi integer not null,
  label text
);

create table public.device_status (
  id integer primary key check (id = 1),
  rfid_active integer not null default 1 check (rfid_active in (0, 1)),
  rfid_uid text,
  tx_power integer not null default 20 check (tx_power between 0 and 33),
  connection_status text not null default 'Connected'
);

create table public.book_loans (
  id text primary key,
  member_id text not null references public.members(id) on delete restrict,
  member_name text not null,
  member_nim text not null,
  book_id text not null references public.books(id) on delete restrict,
  book_tag_id text,
  book_title text not null,
  book_isbn text not null,
  borrowed_at date not null default current_date,
  due_at date not null,
  returned_at date,
  status text not null check (status in ('Dipinjam', 'Dikembalikan')) default 'Dipinjam',
  check (due_at >= borrowed_at),
  check (returned_at is null or returned_at >= borrowed_at)
);

create unique index book_loans_one_active_member_uidx
  on public.book_loans (member_id)
  where status = 'Dipinjam';

create unique index book_loans_active_tag_uidx
  on public.book_loans (regexp_replace(upper(book_tag_id), '[^A-Z0-9]', '', 'g'))
  where status = 'Dipinjam' and book_tag_id is not null;

create index visitor_logs_waktu_idx on public.visitor_logs (waktu desc);
create index book_logs_waktu_idx on public.book_logs (waktu desc);
create index activities_waktu_idx on public.activities (waktu desc);
create index book_loans_status_due_idx on public.book_loans (status, due_at);

