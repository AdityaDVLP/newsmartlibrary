create extension if not exists pgcrypto;

create table if not exists public.members (
  id text primary key,
  nim text not null,
  nama text not null,
  prodi text not null,
  email text,
  no_hp text,
  rfid_tag text not null unique,
  status text not null check (status in ('Mahasiswa', 'Dosen', 'Visitor')),
  date_registered date not null default current_date
);

create table if not exists public.books (
  id text primary key,
  isbn text not null,
  judul text not null,
  pengarang text,
  penerbit text,
  kategori text,
  lokasi_rak text,
  rfid_tag text not null unique,
  epc_list text[] default array[]::text[],
  status text not null check (status in ('Tersedia', 'Dipinjam', 'Dalam Perawatan')) default 'Tersedia',
  stok integer not null default 0
);

create table if not exists public.visitor_logs (
  id text primary key,
  waktu text not null,
  nama text not null,
  nim text not null,
  prodi text not null,
  kategori text not null check (kategori in ('Mahasiswa', 'Dosen', 'Visitor')),
  status text not null check (status in ('Masuk', 'Keluar', 'Pinjam Buku')),
  rfid_tag text not null,
  email text,
  no_hp text
);

create table if not exists public.book_logs (
  id text primary key,
  waktu text not null,
  isbn text not null,
  judul text not null,
  kategori text,
  lokasi_rak text,
  rssi integer not null,
  rfid_tag text not null
);

create table if not exists public.activities (
  id text primary key,
  waktu text not null,
  deskripsi text not null,
  tipe text not null check (tipe in ('visitor', 'book', 'system', 'member')),
  icon_type text
);

create table if not exists public.rssi_history (
  id bigint generated by default as identity primary key,
  time text not null,
  rssi integer not null,
  label text
);

create table if not exists public.device_status (
  id integer primary key check (id = 1),
  rfid_active integer not null default 1,
  rfid_uid text,
  tx_power integer not null default 20,
  connection_status text not null default 'Connected'
);
